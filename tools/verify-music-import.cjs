'use strict';
const assert=require('assert/strict'),{rank,assessRights}=require('./music-import.cjs');
const source={title:'晴天',artists:['歌手甲','歌手乙'],duration:200};
const same={name:'晴天',artists:[{name:'歌手甲'},{name:'歌手乙'}],duration:200000};
assert.ok(rank(source,same).score>=85);
assert.equal(rank(source,{...same,artists:[{name:'歌手甲'},{name:'歌手丙'}]}).score,0,'A shared producer is not enough to replace the vocalist');
assert.equal(rank(source,{...same,name:'晴天 (Live)'}).score,0);
assert.equal(rank(source,{...same,name:'晴天 (Remix)'}).score,0);
assert.equal(rank(source,{...same,duration:30000}).score,0);
assert.ok(rank({title:'空',artists:['作者（别名）'],duration:200},{name:'空',artists:[{name:'别名'}],duration:200000}).score>=85);
const full={url:'https://audio.test/full.mp3',code:200,time:200000,freeTrialInfo:null};
assert.equal(assessRights({fee:0,dt:200000},full).status,'eligible');
assert.equal(assessRights({fee:8,dt:200000},full).status,'eligible');
assert.equal(assessRights({fee:1,dt:200000},{...full,payed:1}).status,'vip','VIP songs stay excluded even if a logged-in service can stream them');
assert.equal(assessRights({fee:4,dt:200000},full).status,'vip');
assert.equal(assessRights({fee:8,dt:200000},{...full,time:30000,freeTrialInfo:{start:100,end:130}}).status,'preview');
assert.equal(assessRights({fee:0,dt:200000},{...full,time:30000}).status,'preview');
assert.equal(assessRights({fee:0,dt:200000},{...full,url:null}).status,'unavailable');
assert.equal(assessRights({fee:0,dt:200000},{...full,time:100000}).status,'unverified');
console.log('PASS: exact performers/versions/duration, explicit aliases, anonymous free full-length rights, VIP exclusion and trial/unavailable separation.');
